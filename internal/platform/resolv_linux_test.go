package platform

import (
	"net/netip"
	"slices"
	"strings"
	"testing"
)

func addrs(t *testing.T, raw ...string) []netip.Addr {
	t.Helper()
	out := make([]netip.Addr, len(raw))
	for i, r := range raw {
		out[i] = netip.MustParseAddr(r)
	}
	return out
}

func TestParseResolvConf(t *testing.T) {
	tests := []struct {
		name        string
		input       string
		nameservers []string
		search      []string
	}{
		{
			name: "multiple nameservers",
			input: "nameserver 192.168.1.1\n" +
				"nameserver 8.8.8.8\n",
			nameservers: []string{"192.168.1.1", "8.8.8.8"},
		},
		{
			name: "comments stripped",
			input: "# generated by NetworkManager\n" +
				"nameserver 192.168.1.1 # primary\n" +
				"; another comment\n" +
				"nameserver 8.8.8.8;inline\n",
			nameservers: []string{"192.168.1.1", "8.8.8.8"},
		},
		{
			name:        "systemd-resolved stub only",
			input:       "nameserver 127.0.0.53\noptions edns0 trust-ad\nsearch .\n",
			nameservers: []string{"127.0.0.53"},
			search:      []string{"."},
		},
		{
			name:        "ipv6 with zone suffix",
			input:       "nameserver fe80::1%eth0\n",
			nameservers: []string{"fe80::1"},
		},
		{
			name: "search and legacy domain",
			input: "search corp.example.com lab.example.com\n" +
				"domain legacy.example.com\n",
			search: []string{"corp.example.com", "lab.example.com", "legacy.example.com"},
		},
		{
			name:  "garbage skipped",
			input: "nameserver not-an-ip\nnameserver\nbogusline\n",
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			rc, err := parseResolvConf(strings.NewReader(tt.input))
			if err != nil {
				t.Fatalf("parseResolvConf: %v", err)
			}
			var want []netip.Addr
			if len(tt.nameservers) > 0 {
				want = addrs(t, tt.nameservers...)
			}
			if !slices.Equal(rc.Nameservers, want) {
				t.Errorf("nameservers = %v, want %v", rc.Nameservers, want)
			}
			if !slices.Equal(rc.Search, tt.search) {
				t.Errorf("search = %v, want %v", rc.Search, tt.search)
			}
		})
	}
}

func TestAllLoopback(t *testing.T) {
	tests := []struct {
		name  string
		addrs []netip.Addr
		want  bool
	}{
		{"empty", nil, false},
		{"stub only", addrs(t, "127.0.0.53"), true},
		{"ipv6 loopback", addrs(t, "::1"), true},
		{"mixed", addrs(t, "127.0.0.53", "8.8.8.8"), false},
		{"public only", addrs(t, "1.1.1.1"), false},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if got := allLoopback(tt.addrs); got != tt.want {
				t.Errorf("allLoopback(%v) = %v, want %v", tt.addrs, got, tt.want)
			}
		})
	}
}
